'use strict';
const assert=require('node:assert/strict');
const edit=require('./pcm-neural-ui-edit.js');
assert.equal(edit.isEditRequest('Altere o título do painel'),true);
assert.equal(edit.isEditRequest('Mude a cor da interface para verde'),true);
assert.equal(edit.isEditRequest('Edite a resposta anterior para ficar mais curta'),false);
assert.equal(edit.isEditRequest('Edite os registros do painel'),false);
assert.equal(edit.isEditRequest('Como faço para mudar a cor do dashboard?'),false);
assert.equal(edit.parse('{"action":"title","value":"Monitoramento de Bombas"}').action,'title');
assert.deepEqual(edit.parse('{"action":"accent","value":"green"}'),{action:'accent',value:'green'});
assert.equal(edit.parse('{"action":"script","value":"alert(1)"}'),null);
assert.equal(edit.parse('{"action":"title","value":"<h1>inseguro</h1>"}'),null);
assert.equal(edit.parse('{"action":"accent","value":"#00FF00"}'),null);
assert.equal(edit.parse('Sem JSON'),null);
assert.equal(edit.parse('{"action":"none","value":""}'),null);
const heading={textContent:'Visão dos sistemas'};
const root={dataset:{},style:{vars:{},setProperty(k,v){this.vars[k]=v;}}};
globalThis.document={documentElement:root,querySelector:q=>q==='#pageTitle'?heading:null};
assert.equal(edit.apply({action:'title',value:'Monitoramento de Bombas'}),true);
assert.equal(heading.textContent,'Monitoramento de Bombas');
assert.equal(edit.undo(),true);
assert.equal(heading.textContent,'Visão dos sistemas');
assert.equal(edit.apply({action:'accent',value:'teal'}),true);
assert.equal(root.style.vars['--blue'],'#087e8b');
assert.equal(edit.apply({action:'size',value:'large'}),true);
assert.equal(root.dataset.pcmTextSize,'large');
assert.equal(edit.apply({action:'density',value:'compact'}),true);
assert.equal(root.dataset.pcmDensity,'compact');
heading.textContent='Engenharia & Decisão';
edit.onPageChange();
assert.equal(edit.apply({action:'title',value:'Manutenção inteligente'}),true);
assert.equal(heading.textContent,'Manutenção inteligente');
assert.equal(edit.apply({action:'reset',value:''}),true);
assert.equal(heading.textContent,'Engenharia & Decisão');
assert.equal(root.style.vars['--blue'],'#0027bd');
assert.equal(root.dataset.pcmTextSize,'normal');
assert.equal(root.dataset.pcmDensity,'comfortable');
console.log('PCM Qwen editor: edição visual segura, reversão, trocas de página e bloqueio de alterações em registros aprovados.');
